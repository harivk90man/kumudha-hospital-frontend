-- ── Deferred cash_session_id FKs ─────────────────────────────
-- Wire deferred cash_session_id FKs now that cash_sessions exists.
-- pharmacy_sales.cash_session_id was left as a plain uuid column in V57.
-- pharmacy_returns.cash_session_id was left as a plain uuid column in V59.

ALTER TABLE pharmacy_sales
    ADD CONSTRAINT fk_pharmacy_sales_cash_session
    FOREIGN KEY (cash_session_id) REFERENCES cash_sessions(id) ON DELETE RESTRICT;

ALTER TABLE pharmacy_returns
    ADD CONSTRAINT fk_pharmacy_returns_cash_session
    FOREIGN KEY (cash_session_id) REFERENCES cash_sessions(id) ON DELETE RESTRICT;
